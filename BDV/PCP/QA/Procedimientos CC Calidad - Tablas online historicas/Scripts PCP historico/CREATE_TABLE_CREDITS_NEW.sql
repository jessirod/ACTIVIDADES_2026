CREATE INDEX PCP.CREDITS_NEW_N4 ON PCP.CREDITS_NEW (ID_CREDITS, PROCESS_DATE)
  NOLOGGING TABLESPACE INDX PCTFREE 10 INITRANS 2 MAXTRANS 255
