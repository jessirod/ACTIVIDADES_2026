  ID_TDETAIL            NUMBER(18)  NOT NULL,
  RECORD_ENTRY_DATE     TIMESTAMP(6),
  CUSTOMER_ID           VARCHAR2(20 BYTE),
  DIG_CUSTOMER_ID       VARCHAR2(1 BYTE),
  APELLIDO1             VARCHAR2(60 BYTE),
