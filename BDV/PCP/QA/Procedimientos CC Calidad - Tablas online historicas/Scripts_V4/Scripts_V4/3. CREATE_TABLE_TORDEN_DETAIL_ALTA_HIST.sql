  NOMBRE                VARCHAR2(60 BYTE),
  PEDIDO                VARCHAR2(10 BYTE),
  FAMILIA               VARCHAR2(8 BYTE),
  CIUDAD                VARCHAR2(20 BYTE),
  ESTADO                VARCHAR2(25 BYTE),
  COD_OFI               VARCHAR2(4 BYTE),
  SEXO                  VARCHAR2(1 BYTE),
  COD_AREA              VARCHAR2(7 BYTE),
  NRO_TELF              VARCHAR2(8 BYTE),
  DESC_TELF             VARCHAR2(10 BYTE),
  FEC_NAC               VARCHAR2(8 BYTE),
  DESC_CUSTOMER         VARCHAR2(60 BYTE),
  CARD_NUMBER           VARCHAR2(20 BYTE),
  FECH_VENCIM           VARCHAR2(6 BYTE),
  STATUS                NUMBER(2),
